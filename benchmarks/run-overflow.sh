#!/usr/bin/env bash
# What do always-on overflow checks cost?
#
#   sh benchmarks/run-overflow.sh          # regenerates results-overflow-checks.md
#
# Milo traps on `+ - * -x` in EVERY build mode (Swift/Zig model, not Rust's
# debug-trap/release-wrap). That is a language law, not a mode flip — so the price
# belongs in the benchmark table rather than in a claim. Each program is built twice
# at --release, identical but for --no-overflow-checks, and timed head to head.
#
# The table is generated. Do not hand-edit results-overflow-checks.md; the numbers
# there are only as trustworthy as the last run of this script.
#
# Two things this script learned the hard way and encodes so the next reader does not
# repeat them:
#   - Equal file SIZE is not an identical binary. An early pass compared sizes, concluded
#     a float matmul emitted no checks, and put that claim in the language reference. It
#     was false: matmul emits 100 overflow intrinsics, they are just dwarfed by the f64
#     work. The "checks emitted" column below counts intrinsics in the IR instead.
#   - A benchmark that runs in 3ms is measuring process startup. Checks cannot make code
#     faster, so any ratio below 1.00 is noise announcing itself; those rows are marked
#     rather than published as if they meant something.
set -e

DIR="$(cd "$(dirname "$0")" && pwd)"
REPO="$(dirname "$DIR")"
MILO="bun run $REPO/src/main.ts"
OUT="$DIR/results-overflow-checks.md"
RUNS=${RUNS:-20}
WARMUP=${WARMUP:-2}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

command -v hyperfine >/dev/null || { echo "hyperfine required"; exit 1; }

# name:relative-source:runtime-args
BENCHES=(
  "fib:fib/fib.milo:"
  "sieve:sieve/sieve.milo:"
  "binarytrees:binarytrees/binarytrees.milo:"
  "maplookup:maplookup/maplookup.milo:"
  "sort:sort/sort.milo:"
  "matmul:matmul/matmul.milo:"
  "json:json/json.milo:$DIR/json/data.json"
  "grep:grep/grep.milo:the $DIR/grep/input.txt"
)

{
  echo "<!-- generated by benchmarks/run-overflow.sh — do not hand-edit -->"
  echo
  echo "# Cost of always-on overflow checks"
  echo
  echo "Each program built twice at \`--release\`, identical but for \`--no-overflow-checks\`."
  echo "\"Checks emitted\" counts \`llvm.*.with.overflow\` intrinsics in the IR, including the"
  echo "stdlib prelude — the range prover discharges the rest. A benchmark under 5ms is"
  echo "measuring process startup as much as arithmetic; its ratio is marked accordingly."
  echo
  echo "| Benchmark | Checked [ms] | Unchecked [ms] | Ratio | Checks emitted |"
  echo "|:---|---:|---:|---:|---:|"
} > "$OUT"

for entry in "${BENCHES[@]}"; do
  name="${entry%%:*}"; rest="${entry#*:}"
  src="${rest%%:*}"; args="${rest#*:}"
  [ -f "$DIR/$src" ] || { echo "skip $name (no $src)"; continue; }

  $MILO build "$DIR/$src" -o "$TMP/${name}_c" --release >/dev/null 2>&1
  $MILO build "$DIR/$src" -o "$TMP/${name}_u" --release --no-overflow-checks >/dev/null 2>&1

  checks=$($MILO emit-ir "$DIR/$src" 2>/dev/null | grep -c "with.overflow" || true)

  hyperfine -N --warmup "$WARMUP" --runs "$RUNS" \
    --export-json "$TMP/$name.json" \
    "$TMP/${name}_c $args" "$TMP/${name}_u $args" >/dev/null 2>&1

  python3 - "$TMP/$name.json" "$name" "$checks" >> "$OUT" <<'PY'
import json,sys
d=json.load(open(sys.argv[1]))["results"]
c,u=d[0]["mean"]*1000,d[1]["mean"]*1000
r=c/u
# Below 1.00 is impossible: a check cannot speed code up. Say "noise" rather than
# publishing a number that reads as a finding.
note=f'{r:.2f}x' if r>=1.0 else f'{r:.2f}x (noise)'
if max(c,u)<5.0: note+=' ⚠ startup-dominated'
print(f'| `{sys.argv[2]}` | {c:.1f} | {u:.1f} | {note} | {sys.argv[3]} |')
PY
  echo "  $name done"
done

echo "wrote $OUT"
